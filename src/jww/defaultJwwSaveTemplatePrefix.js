let cachedDefaultJwwSaveTemplatePrefix = null;

function decodeBase64Bytes(value) {
  if (typeof atob === "function") {
    const binary = atob(value);
    const bytes = new Uint8Array(binary.length);
    for (let index = 0; index < binary.length; index += 1) {
      bytes[index] = binary.charCodeAt(index);
    }
    return bytes;
  }
  if (typeof Buffer !== "undefined") {
    return Uint8Array.from(Buffer.from(value, "base64"));
  }
  throw new Error("No base64 decoder is available");
}

export function getDefaultJwwSaveTemplatePrefix() {
  if (!cachedDefaultJwwSaveTemplatePrefix) {
    cachedDefaultJwwSaveTemplatePrefix = decodeBase64Bytes(
      DEFAULT_JWW_SAVE_TEMPLATE_PREFIX_BASE64
    );
  }
  return cachedDefaultJwwSaveTemplatePrefix;
}
